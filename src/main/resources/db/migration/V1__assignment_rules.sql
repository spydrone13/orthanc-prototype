create table assignment_rule (
    id                uuid         not null primary key,
    name              varchar(255) not null,
    priority          integer      not null,
    enabled           boolean      not null,
    target_machine_id varchar(255) not null,
    version           bigint       not null,
    constraint uk_assignment_rule_priority unique (priority)
);

create table assignment_rule_condition (
    id              bigint generated by default as identity primary key,
    rule_id         uuid        not null,
    condition_index integer     not null,
    attribute       varchar(32) not null,
    operator        varchar(32) not null,
    constraint fk_condition_rule foreign key (rule_id) references assignment_rule (id) on delete cascade
);

create table assignment_rule_condition_operand (
    condition_id  bigint        not null,
    operand_index integer       not null,
    operand_value varchar(1024) not null,
    primary key (condition_id, operand_index),
    constraint fk_operand_condition foreign key (condition_id) references assignment_rule_condition (id) on delete cascade
);
